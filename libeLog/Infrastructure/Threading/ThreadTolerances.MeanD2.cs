        public static readonly string[] MeanFields = { "3h4h", "4g", "4h", "5h4h", "5g6g", "5h6h", "6d", "6e", "6f", "6g", "6h", "7e6e", "7g6g", "7h6h", "8g" };

        public readonly record struct MeanD2Result(
            string Field, double Nominal, double Max, double Min, int Es, int Ei);

        public static double MeanD2Nominal(double diameter, double pitch)
            => Math.Round(diameter - 0.649519 * pitch, 3, MidpointRounding.AwayFromZero);

        /// <summary>Пределы среднего диаметра d2 наружной резьбы. null — нет данных для сочетания.</summary>
        public static MeanD2Result? GetMeanD2(double diameter, double pitch, string field)
        {
            int r = DiameterRangeIndex(diameter);
            if (r > 8) return null;
            if (!_MeanD2.TryGetValue((r, (int)Math.Round(pitch * 100), field), out var dev)) return null;
            double nom = MeanD2Nominal(diameter, pitch);
            return new(field, nom,
                Math.Round(nom + dev.Es / 1000.0, 3, MidpointRounding.AwayFromZero),
                Math.Round(nom + dev.Ei / 1000.0, 3, MidpointRounding.AwayFromZero),
                dev.Es, dev.Ei);
        }

        /// <summary>Шаги, для которых есть данные es/ei в диапазоне диаметра D.</summary>
        public static double[] PitchesForDiameter(double diameter)
        {
            int r = DiameterRangeIndex(diameter);
            return _MeanD2.Keys.Where(k => k.Item1 == r).Select(k => k.Item2 / 100.0).Distinct().OrderBy(p => p).ToArray();
        }

        /// <summary>Поля допуска, для которых есть данные при D и P.</summary>
        public static string[] FieldsForDiameterAndPitch(double diameter, double pitch)
        {
            int r = DiameterRangeIndex(diameter);
            int pk = (int)Math.Round(pitch * 100);
            return MeanFields.Where(f => _MeanD2.ContainsKey((r, pk, f))).ToArray();
        }

